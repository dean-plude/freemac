#!/bin/sh
# SPDX-License-Identifier: GPL-3.0-or-later
# Writes a source file that makes a framework carry every Objective-C protocol
# its SDK headers declare. On a Mac each framework's binary holds the
# protocols its headers define, so objc_getProtocol("CALayerDelegate") finds
# one even when no class adopts it; programs that build classes at run time
# (Rust's objc crates, Python's PyObjC) add a protocol they fetch by name and
# stop if it is missing. Clang emits a protocol's description wherever
# @protocol(Name) is used, so listing them here is enough (freemac 1.268).
#
#   gen-protocols.sh AppKit AVFoundation ... > appkit/FerryProtocols.m
set -eu
dir=$(cd "$(dirname "$0")" && pwd)/include
echo "/* Generated by sdk/gen-protocols.sh $*; don't edit. */"
echo "#import <Foundation/Foundation.h>"
names=""
for fw in "$@"; do
    for h in $(grep -lE '^@protocol [A-Za-z_0-9]+([^;A-Za-z_0-9].*)?$' "$dir/$fw"/*.h 2>/dev/null | sort); do
        echo "#import <$fw/$(basename "$h")>"
        names="$names $(grep -hoE '^@protocol [A-Za-z_0-9]+([^;A-Za-z_0-9].*)?$' "$h" | awk '{print $2}' | sed 's/[^A-Za-z_0-9].*//')"
    done
done
echo
echo "__attribute__((used)) static void ferry_protocols(void)"
echo "{"
for n in $(printf '%s\n' $names | sort -u); do
    [ "$n" = NSObject ] && continue
    echo "    (void)@protocol($n);"
done
echo "}"
