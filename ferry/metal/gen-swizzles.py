# Writes the swizzle members of Ferry's Metal Shading Language vectors
# (msl/__metal_swizzle_N.h, N = 2, 3, 4), included inside the vector class.
# A swizzle is a property (clang's __declspec(property)) with a getter that
# builds a new vector and, when no component repeats, a setter. Single
# components (.x, .r) are real members of the vector's union instead, so they
# can be bound to references.
import itertools, sys, os
out = sys.argv[1] if len(sys.argv) > 1 else "msl"
for n in (2, 3, 4):
    lines = ["/* Generated by gen-swizzles.py: swizzles of a %d-component vector. */" % n]
    for names in ("xyzw", "rgba"):
        comps = names[:n]
        for length in (2, 3, 4):
            for combo in itertools.product(range(n), repeat=length):
                name = "".join(comps[i] for i in combo)
                args = ", ".join("this->c[%d]" % i for i in combo)
                lines.append("__FERRY_SWG(%s, %d, %s)" % (name, length, args))
                if len(set(combo)) == length:
                    sets = " ".join("this->c[%d] = __v.c[%d];" % (i, k) for k, i in enumerate(combo))
                    lines.append("__FERRY_SWS(%s, %d, %s)" % (name, length, sets))
                    lines.append("__declspec(property(get = __g_%s, put = __s_%s)) vec<T, %d> %s;" % (name, name, length, name))
                else:
                    lines.append("__declspec(property(get = __g_%s)) vec<T, %d> %s;" % (name, length, name))
    with open(os.path.join(out, "__metal_swizzle_%d.h" % n), "w") as f:
        f.write("\n".join(lines) + "\n")
